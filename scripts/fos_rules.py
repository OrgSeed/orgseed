"""Compile the rules in force into org/RULES_IN_FORCE.md.

Usage:  python scripts/fos_rules.py

Includes: a pointer to the core rules (AGENTS.md, always in force); the rules of every
module that is on AND adopted by a decision the founder signed; the founder's own rules
(org/OUR_RULES.md) and norms (org/NORMS.md) whose adopted_by points to such a decision.
Entries without one are listed separately as proposals.

The output depends only on the organization's files (no clock), so the same files always
give the same rules file, and scripts/fos_check.py can tell when it is out of date.

settings.rule_reasons in org/config.json: "shown" (default) keeps each rule's why and
literature line; "hidden" drops them (for studies comparing the two only).
Standard library only; no network.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fos_lib as L  # noqa: E402


def render_entry(e, reasons, extra=("norm", "guards_against", "review_by")):
    out = ["### %s %s" % (e["id"], e.get("title", ""))]
    if e.get("rule"):
        out.append("rule: " + e["rule"])
    for k in extra:
        if e.get(k) and (reasons or k == "norm"):
            out.append("%s: %s" % (k, e[k]))
    if reasons:
        if e.get("why"):
            out.append("why: " + e["why"])
        if e.get("lit"):
            out.append("lit: " + e["lit"])
    out.append("")
    return out


def build(cfg=None, records=None):
    cfg = cfg or L.config()
    records = records or L.read_all()
    ok_ids = L.adoption(cfg, records)["signed"]
    reasons = cfg.get("settings", {}).get("rule_reasons", "shown") != "hidden"
    mods = L.modules_in_force(cfg, ok_ids)
    core = L.core_rule_ids()
    core_text = ("The core rules %s to %s are in AGENTS.md." % (core[0], core[-1])) if core else \
        "The core rules are in AGENTS.md."
    lines = [
        "# Rules in force",
        "",
        "Generated by scripts/fos_rules.py from the organization's files. Do not edit by hand; change the "
        "organization through proposals, decisions and the founder's signature, then regenerate.",
        "",
        "Config hash: %s" % L.config_hash(),
        "Modules in force: %s" % (", ".join(mods) or "none"),
        "Rule reasons: %s" % ("shown" if reasons else "hidden"),
        "",
        "## Core (always in force)",
        "",
        core_text,
        "",
    ]
    for m in mods:
        lines += ["## Module: %s" % m, ""]
        for e in L.module_rules(m):
            lines += render_entry(e, reasons)
    pending = []
    for rel, label in (("org/OUR_RULES.md", "Our rules"), ("org/NORMS.md", "Norms")):
        entries = L.parse_entries(L.read_text(rel, ""))
        adopted = [e for e in entries if L.governed(e.get("adopted_by"), ok_ids)
                   and e.get("adopted_by") not in ("core", "seed")]
        pending += [(rel, e) for e in entries if e not in adopted]
        if adopted:
            lines += ["## %s (%s)" % (label, rel), ""]
            for e in adopted:
                lines += render_entry(e, reasons)
    if pending:
        lines += ["## Proposed, not in force", ""]
        for rel, e in pending:
            lines.append("- %s %s (%s): no signed adopting decision" % (e["id"], e.get("title", ""), rel))
        lines.append("")
    return "\n".join(lines), mods, reasons


def main():
    text, mods, reasons = build()
    with open(L.path("org/RULES_IN_FORCE.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote org/RULES_IN_FORCE.md (modules in force: %s; reasons %s)"
          % (", ".join(mods) or "none", "shown" if reasons else "hidden"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
